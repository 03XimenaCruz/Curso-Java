public class Ope_Logicos {
    public static void main(String[] args) {
        boolean a = true, b= false;
        //OPERADOR AND (Y)
        System.out.println(a && b);
        //OPERADOR OR (O)
        System.out.println(a || b);
        //OPERADOR NOT (NO)
        System.out.println(!a);
        //XOR LOGICO
        System.out.println(a ^ b);
    }
}
